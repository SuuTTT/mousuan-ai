def register_cjk_font() -> str:
    candidates = [
        ("/System/Library/Fonts/STHeiti Medium.ttc", 0),
        ("/System/Library/Fonts/Hiragino Sans GB.ttc", 0),
        ("/Library/Fonts/Arial Unicode.ttf", None),
    ]
    for path, subfont_index in candidates:
        if not Path(path).exists():
            continue
        try:
            if subfont_index is None:
                pdfmetrics.registerFont(TTFont("ReviewCJK", path))
            else:
                pdfmetrics.registerFont(TTFont("ReviewCJK", path, subfontIndex=subfont_index))
            return "ReviewCJK"
        except Exception:
            continue
    raise RuntimeError("No usable Chinese-capable font was found")


