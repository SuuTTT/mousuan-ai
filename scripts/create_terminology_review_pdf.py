    canvas.setStrokeColor(colors.HexColor("#d8dced"))
    canvas.line(16 * mm, 13 * mm, PAGE_W - 16 * mm, 13 * mm)
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#69738c"))
    canvas.drawString(16 * mm, 8 * mm, "MouSuan Strategy terminology review sheet")
    canvas.drawRightString(PAGE_W - 16 * mm, 8 * mm, f"Page {doc.page}")
    canvas.restoreState()


